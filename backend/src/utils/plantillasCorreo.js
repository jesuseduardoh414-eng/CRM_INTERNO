// Campos editables y su largo maximo.
const CAMPOS_TEXTO = { asunto: 150, titulo: 150, cuerpo: 2000, boton: 40, nota: 500 };

const PLANTILLAS_POR_ID = Object.fromEntries(PLANTILLAS.map((p) => [p.id, p]));

/** Campos que una plantilla permite editar (el boton solo si lleva boton). */
const camposDe = (plantilla) => Object.keys(CAMPOS_TEXTO).filter((campo) => campo !== 'boton' || plantilla.extras.boton);

/** Valores de ejemplo para la vista previa. */
const ejemplosDe = (plantilla) => Object.fromEntries(plantilla.variables.map((v) => [v, V[v]?.ejemplo || v]));

/** Catalogo para el panel: textos de fabrica y variables con su descripcion. */
// Las plantillas de un modulo retirado (portal de clientes) no se ofrecen en
// el panel; siguen definidas por si el modulo vuelve.
const MODULOS_RETIRADOS_CORREO = ['portalClientes'];
const catalogo = () => PLANTILLAS.filter((p) => !MODULOS_RETIRADOS_CORREO.includes(p.modulo)).map((p) => ({
  id: p.id,
  grupo: p.grupo,
  nombre: p.nombre,
  descripcion: p.descripcion,
  extras: p.extras,
  campos: camposDe(p),
  variables: [
    ...p.variables.map((v) => ({ clave: v, descripcion: V[v]?.descripcion || v })),
    ...Object.entries(VARIABLES_GLOBALES).map(([clave, info]) => ({ clave, descripcion: info.descripcion })),
  ],
  fabrica: Object.fromEntries(camposDe(p).map((campo) => [campo, p[campo]])),
}));

module.exports = {
  PLANTILLAS,
  PLANTILLAS_POR_ID,
  CAMPOS_TEXTO,
  VARIABLES_GLOBALES,
  camposDe,
  ejemplosDe,
  catalogo,
};
